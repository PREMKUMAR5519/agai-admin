import { test, expect } from '@playwright/test'
import sharp from 'sharp'

test('library deletion requires a fresh admin password and refreshes storage after success', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Email address').fill('editor@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-2026!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Media library', exact: true }).click()
  const before = await (await page.request.get('/api/media/storage')).json()
  const buffer = await sharp({ create: { width: 240, height: 180, channels: 3, background: '#4d83a3' } }).png().toBuffer()
  const uploadResponse = page.waitForResponse(response => response.url().endsWith('/api/media') && response.request().method() === 'POST')
  await page.locator('input[type=file]').setInputFiles({ name: 'image-to-delete.png', mimeType: 'image/png', buffer })
  const uploaded = await (await uploadResponse).json()
  const meter = page.getByRole('progressbar', { name: 'Image storage used' })
  await expect(meter).toHaveAttribute('value', String(before.usedBytes + uploaded.size))
  const deleteButton = page.getByRole('button', { name: 'Delete image image-to-delete.png', exact: true })
  await deleteButton.click()
  const dialog = page.getByRole('dialog', { name: 'Delete image?', exact: true })
  const password = dialog.getByLabel('Admin password', { exact: true })
  const confirm = dialog.getByRole('button', { name: 'Delete image permanently', exact: true })
  await expect(confirm).toBeDisabled()
  await expect(password).toHaveAttribute('type', 'password')
  await expect(password).toBeFocused()
  await expect(dialog).toContainText('deleting it will leave a missing image')
  await password.fill('discard-on-cancel')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(deleteButton).toBeFocused()
  await deleteButton.click()
  await expect(password).toHaveValue('')
  await password.fill('incorrect-password')
  await confirm.click()
  await expect(dialog.getByRole('alert')).toContainText('Admin password is incorrect')
  await expect(password).toHaveValue('')
  await expect(password).toBeFocused()
  expect((await (await page.request.get('/api/media')).json()).some(item => item._id === uploaded._id)).toBe(true)
  expect((await (await page.request.get('/api/media/storage')).json()).usedBytes).toBe(before.usedBytes + uploaded.size)
  await page.setViewportSize({ width: 320, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/media-delete-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  expect((await dialog.boundingBox()).width).toBeLessThanOrEqual(480)
  await page.screenshot({ path: 'test-results/media-delete-desktop.png', fullPage: true })
  await page.route(`**/api/media/${uploaded._id}`, route => route.fulfill({ status: 503, json: { message: 'Image deletion could not finish. Please try deleting it again.' } }), { times: 1 })
  await password.fill('Browser-test-password-2026!')
  await confirm.click()
  await expect(dialog.getByRole('alert')).toContainText('Please try deleting it again')
  await expect(password).toHaveValue('')
  await password.fill('Browser-test-password-2026!')
  await confirm.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Image permanently deleted')
  await expect(deleteButton).toHaveCount(0)
  await expect(meter).toHaveAttribute('value', String(before.usedBytes))
  expect((await page.request.get(`/uploads/${uploaded.filename}`)).status()).toBe(404)
  await page.reload()
  await expect(deleteButton).toHaveCount(0)
  await expect(meter).toHaveAttribute('value', String(before.usedBytes))
  expect(errors).toEqual([])
})
