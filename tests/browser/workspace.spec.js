test('services dashboard shows loading and can retry a failed API request', async ({ page }) => {
  await login(page)
  let fail = true
  let release = () => {}
  const waiting = new Promise(resolve => { release = resolve })
  await page.route('**/api/services', async route => {
    if (fail) return route.fulfill({ status: 503, json: { message: 'Services temporarily unavailable' } })
    await waiting
    return route.continue()
  })
  await page.getByRole('link', { name: 'Website content', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Services temporarily unavailable')
  fail = false
  await page.getByRole('button', { name: 'Retry loading services' }).click()
  await expect(page.getByRole('status')).toContainText('Loading your workspace')
  release()
  await expect(page.getByRole('heading', { name: 'Your services.' })).toBeVisible()
})

