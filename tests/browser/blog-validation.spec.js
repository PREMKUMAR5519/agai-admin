import { test, expect } from '@playwright/test'

test('Save and Publish from Preview reveal invalid fields without losing the draft', async ({ page }) => {
  const errors = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByLabel('Email address').fill('editor@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-2026!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'New blog', exact: true }).click()
  let writes = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/posts')) writes++ })
  async function invalidFromPreview(action, field, message) {
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await page.getByRole('button', { name: action, exact: true }).click()
    await expect(page.getByRole('alert')).toContainText(message)
    await expect(field).toBeVisible()
    await expect(field).toBeFocused()
    await expect(field).toHaveAttribute('aria-invalid', 'true')
    expect(writes).toBe(0)
  }
  const title = page.getByLabel('Article title', { exact: true })
  await title.fill('   ')
  await invalidFromPreview('Save draft', title, 'Enter an article title')
  await title.fill('A preview validation regression')
  const excerpt = page.getByLabel('Short introduction', { exact: true })
  await invalidFromPreview('Publish article', excerpt, 'Enter a short introduction')
  await excerpt.fill('The draft should survive every validation error.')
  const category = page.getByLabel('Category', { exact: true })
  await category.fill('')
  await invalidFromPreview('Save draft', category, 'Enter a category')
  await category.fill('Movement goals')
  const slug = page.getByLabel('URL slug', { exact: true })
  await slug.fill('Invalid Slug!')
  await invalidFromPreview('Publish article', slug, 'lowercase words separated by hyphens')
  await slug.fill('preview-validation-regression')
  const image = page.getByLabel('Image URL', { exact: true })
  await image.fill('not-a-valid-url')
  await invalidFromPreview('Save draft', image, 'complete http:// or https:// image URL')
  await image.fill('')
  const body = page.getByRole('textbox', { name: 'Blog content', exact: true })
  await invalidFromPreview('Publish article', body, 'Write some blog content')
  await body.fill('Content kept while correcting fields and moving between editor and preview.')
  await expect(title).toHaveValue('A preview validation regression')
  await expect(excerpt).toHaveValue('The draft should survive every validation error.')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await page.getByRole('button', { name: 'Publish article', exact: true }).click()
  await expect(page).toHaveURL(/\/journal\/[a-f\d]{24}$/)
  await expect(page.locator('.status-line .badge')).toHaveText('Published')
  const savedId = new URL(page.url()).pathname.split('/').at(-1)
  const saved = await (await page.request.get(`/api/posts/${savedId}`)).json()
  expect(saved.published.title).toBe('A preview validation regression')
  expect(writes).toBe(1)
  expect(errors.filter(message => message.includes('not focusable'))).toEqual([])
})
