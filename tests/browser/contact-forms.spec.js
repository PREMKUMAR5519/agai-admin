import { test, expect } from '@playwright/test'

test('website enquiries persist and are visible only in the admin inbox', async ({ page, context, request }) => {
  const website = await context.newPage()
  await website.goto(`http://127.0.0.1:${process.env.E2E_WEBSITE_PORT || 5190}/contact`)
  await website.getByLabel('Your name').fill('Website Contact Test')
  await website.getByLabel('Phone number').fill('+91 98765 43210')
  await website.getByLabel('Email address').fill('visitor@example.com')
  await website.getByLabel('Your message').fill('Please call me about a visit next week. <script>unsafe</script>')
  // A transient failure must preserve the visitor's message for retry.
  await website.route('**/api/public/contact', route => route.fulfill({ status: 503, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ message: 'Please try again.' }) }))
  await website.getByRole('button', { name: 'Submit enquiry' }).click()
  await expect(website.getByRole('alert')).toContainText('Please try again')
  await expect(website.getByLabel('Your message')).toHaveValue(/Please call me/)
  await website.unroute('**/api/public/contact')
  await website.getByRole('button', { name: 'Submit enquiry' }).click()
  await expect(website.getByRole('heading', { name: 'Enquiry received.' })).toBeVisible()
  await expect(website.getByLabel('Your name')).toHaveValue('')
  expect((await request.get('/api/contact-submissions')).status()).toBe(401)
  await page.goto('/contact-forms')
  await page.getByLabel('Email address').fill('editor@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-2026!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const entry = page.locator('.contact-entry').filter({ hasText: 'Website Contact Test' })
  await expect(entry).toBeVisible()
  await entry.getByText('Read message').click()
  await expect(entry.locator('.contact-message')).toContainText('<script>unsafe</script>')
  await expect(entry.getByRole('link', { name: 'visitor@example.com' })).toBeVisible()
  await page.reload()
  await expect(entry).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  await page.screenshot({ path: 'test-results/contact-inbox-mobile.png', fullPage: true })
})
